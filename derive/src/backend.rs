use proc_macro2::{Span, TokenStream};
use quote::{format_ident, quote, quote_spanned};
use syn::{Ident, spanned::Spanned};

use crate::model::{Container, Field, FieldKind, Mode, ValueField};

mod env_vars;

pub fn expand(container: &Container) -> TokenStream {
    let vis = &container.vis;
    let ident = &container.ident;
    let (impl_generics, ty_generics, where_clause) = container.generics.split_for_impl();
    let fields = &container.fields;

    let errors = Ident::new("errors", Span::mixed_site());
    let field_idents = fields.iter().map(|field| &field.ident);
    let locals: Vec<Ident> = (0..fields.len())
        .map(|i| format_ident!("field_{}", i, span = Span::mixed_site()))
        .collect();
    let collects = fields.iter().map(|field| field_collect(field, &errors));
    let env_vars = env_vars::env_vars(container, env_vars::Placement::TopLevel);
    let nested_env_vars = env_vars::env_vars(container, env_vars::Placement::Nested);

    let body = if fields.is_empty() {
        quote! { ::core::result::Result::Ok(Self {}) }
    } else {
        quote! {
            let mut #errors = ::typenv::__private::ErrorCollector::new();

            #( let #locals = #collects; )*

            let (#(::core::option::Option::Some(#locals),)*) = (#(#locals,)*) else {
                return ::core::result::Result::Err(#errors.finish());
            };

            ::core::result::Result::Ok(Self { #(#field_idents: #locals,)* })
        }
    };

    quote! {
        impl #impl_generics ::typenv::FromEnv for #ident #ty_generics #where_clause {
            const ENV_VARS: &'static str = #env_vars;
            const __NESTED_ENV_VARS: &'static str = #nested_env_vars;

            fn from_env() -> ::core::result::Result<Self, ::typenv::FromEnvErrors> {
                #body
            }
        }

        // Lets users call `Type::from_env()` and use `Type::ENV_VARS` without importing the trait.
        impl #impl_generics #ident #ty_generics #where_clause {
            /// The environment variables this struct reads, one per line, with whether they are
            /// optional or defaulted. Variables of nested structs also name the field they are
            /// loaded into.
            ///
            /// Generated by `#[derive(FromEnv)]`; equivalent to `typenv::FromEnv::ENV_VARS`.
            #[allow(dead_code)]
            #vis const ENV_VARS: &'static str = <Self as ::typenv::FromEnv>::ENV_VARS;

            /// Loads this struct from environment variables, reporting every missing or invalid
            /// variable at once.
            ///
            /// Generated by `#[derive(FromEnv)]`; equivalent to calling
            /// `typenv::FromEnv::from_env`.
            #[allow(dead_code)]
            #vis fn from_env() -> ::core::result::Result<Self, ::typenv::FromEnvErrors> {
                <Self as ::typenv::FromEnv>::from_env()
            }
        }
    }
}

/// An expression that loads one field, evaluating to `Option<T>`: `Some` on success, `None` after
/// recording the error(s) in `errors`.
fn field_collect(field: &Field, errors: &Ident) -> TokenStream {
    let path = &field.path;
    let span = field.span;

    match &field.kind {
        FieldKind::Nested { ty } => quote_spanned! {span=>
            #errors.handle_nested(#path, <#ty as ::typenv::FromEnv>::from_env())
        },
        FieldKind::Value(value) => {
            let call = value_call(path, span, value);
            quote! { #errors.handle(#call) }
        }
    }
}

fn value_call(path: &str, span: Span, value: &ValueField) -> TokenStream {
    let ValueField {
        var,
        ty,
        parser,
        mode,
    } = value;

    let parser = match parser {
        Some(parser) => quote_spanned! {parser.span()=> &(#parser) },
        // `FromStr` if implemented, otherwise `TryFrom<String>` (which includes `From<String>`),
        // otherwise a readable compile error. See `typenv::__private::Wrap`.
        None => quote_spanned! {span=>
            &{
                // Only one of the traits applies to a given type.
                #[allow(unused_imports)]
                use ::typenv::__private::{ViaFallback as _, ViaFromStr as _, ViaTryFrom as _};
                (&&&::typenv::__private::Wrap::<#ty>::new()).__typenv_default_parser()
            }
        },
    };

    // The explicit `::<#ty>` lets generic parsers such as `parser::json` infer
    // their output type from the field.
    match mode {
        Mode::Required => quote_spanned! {span=>
            ::typenv::__private::required::<#ty>(#path, #var, #parser)
        },
        Mode::Optional => quote_spanned! {span=>
            ::typenv::__private::optional::<#ty>(#path, #var, #parser)
        },
        Mode::Default(default) => quote_spanned! {span=>
            ::typenv::__private::with_default::<#ty>(#path, #var, #default, #parser)
        },
        Mode::DefaultValue(value) => {
            // Spanned at the expression so a type mismatch points at it.
            let default = quote_spanned! {value.span()=> || #value };
            quote_spanned! {span=>
                ::typenv::__private::with_default_value::<#ty>(#path, #var, #default, #parser)
            }
        }
    }
}
